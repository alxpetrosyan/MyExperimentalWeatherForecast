export const translateCondition = (value: string, t: (key: string) => string) => {
  const key = value.toLowerCase();
  if (key.includes("partly cloudy")) return t("partCloudy");
  if (key.includes("light rain")) return t("lightRain");
  if (key.includes("breezy with passing showers")) return t("breezyShowers");
  if (key.includes("comfortable with mixed clouds")) return t("mixedClouds");
  if (key.includes("live forecast")) return t("liveForecast");
  if (key.includes("hourly")) return t("hourlyCondition");
  if (key.includes("comfortable with variable clouds")) return t("variableClouds");
  return value;
};
